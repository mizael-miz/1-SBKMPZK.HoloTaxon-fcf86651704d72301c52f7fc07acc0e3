import esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";

// Obsidian evaluates a plugin's main.js as a string inside its own loader, so
// the entry point cannot rely on Node's file-based module resolution. The
// build therefore bundles the TypeScript sources into one self-contained
// CommonJS main.js. The "obsidian" module is provided by the host application
// and stays external.
const root = process.cwd();
const watch = process.argv.includes("--watch");

const options = {
  entryPoints: [path.join(root, "src", "main.ts")],
  outfile: path.join(root, "main.js"),
  bundle: true,
  format: "cjs",
  platform: "browser",
  target: "es2018",
  external: ["obsidian"],
  sourcemap: false,
  banner: { js: "/* Generated by npm run build. Do not edit by hand. */" },
  logLevel: "info",
};

fs.copyFileSync(path.join(root, "src", "styles.css"), path.join(root, "styles.css"));

if (watch) {
  const context = await esbuild.context(options);
  await context.watch();
  console.log("HoloTaxon watch active: watching JavaScript; stylesheet copied at startup");
} else {
  await esbuild.build(options);
  console.log("HoloTaxon build complete: bundled main.js, styles.css");
}
