import fs from "node:fs";
import path from "node:path";

// Obsidian loads root main.js. This bootstrap preserves TypeScript's default export
// while allowing the implementation to remain split into maintainable local modules.
fs.writeFileSync("main.js", '/* Generated by npm run build. Do not edit by hand. */\nmodule.exports = require("./dist/main.js");\n', "utf8");
fs.copyFileSync(path.join("src", "styles.css"), "styles.css");
console.log("HoloTaxon build complete: main.js, dist/*.js, styles.css");
