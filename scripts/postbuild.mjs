import fs from "node:fs";
import path from "node:path";

// Obsidian loads root main.js and expects the plugin constructor itself.
// TypeScript emits the default-exported class as module.exports.default in CommonJS.
fs.writeFileSync("main.js", '/* Generated by npm run build. Do not edit by hand. */\nmodule.exports = require("./dist/main.js").default;\n', "utf8");
fs.copyFileSync(path.join("src", "styles.css"), "styles.css");
console.log("HoloTaxon build complete: main.js, dist/*.js, styles.css");
